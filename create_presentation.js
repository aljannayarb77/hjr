// دالة مساعدة لإضافة الترويسة والتذييل الموحد للشرائح
function addSlideHeaderFooter(slide, slideNum, title, category) {
  slide.background = { color: COLOR_BG };

  // الشريط العلوي (الهيدر)
  slide.addShape(SHAPE_RECT, {
    x: 0, y: 0, w: 13.333, h: 0.95,
    fill: { color: COLOR_PRIMARY },
    line: { color: COLOR_PRIMARY }
  });

  // خط ذهبي فاخر أسفل الهيدر
  slide.addShape(SHAPE_RECT, {
    x: 0, y: 0.93, w: 13.333, h: 0.04,
    fill: { color: COLOR_GOLD },
    line: { color: COLOR_GOLD }
  });

  // شارة التصنيف (يمين أو يسار)
  slide.addShape(SHAPE_ROUND_RECT, {
    x: 0.6, y: 0.22, w: 2.6, h: 0.5,
    rectRadius: 0.08,
    fill: { color: COLOR_GOLD },
    line: { color: COLOR_GOLD }
  });

  slide.addText(category, {
    x: 0.6, y: 0.22, w: 2.6, h: 0.5,
    fontSize: 12, bold: true, color: COLOR_PRIMARY,
    align: 'center', fontFace: 'Calibri'
  });

  // عنوان الشريحة الرئيسي
  slide.addText(title, {
    x: 3.4, y: 0.12, w: 9.3, h: 0.7,
    fontSize: 21, bold: true, color: COLOR_WHITE,
    rtl: true, align: 'right', fontFace: 'Calibri'
  });

  // الشريط السفلي (الفوتر)
  slide.addShape(SHAPE_RECT, {
    x: 0, y: 7.15, w: 13.333, h: 0.35,
    fill: { color: COLOR_PRIMARY },
    line: { color: COLOR_PRIMARY }
  });

  slide.addText('عرض إيجاز قيادي - سري ومحدد التداول | مشروع تنظيم تفويج حِجر إسماعيل بالمسجد الحرام', {
    x: 2.5, y: 7.17, w: 10.2, h: 0.28,
    fontSize: 10, color: COLOR_GOLD,
    rtl: true, align: 'right', fontFace: 'Calibri'
  });

  slide.addText(`شريحة ${slideNum}`, {
    x: 0.6, y: 7.17, w: 1.8, h: 0.28,
    fontSize: 10, color: COLOR_WHITE,
    align: 'left', fontFace: 'Calibri'
  });
}

// دالة مساعدة لإنشاء شريحة صفحة تفصيلية مع لقطة الشاشة والأزرار
function createPageSlide(slideNum, title, category, screenshotName, descText, buttonsList, impactText) {
  const slide = pres.addSlide();
  addSlideHeaderFooter(slide, slideNum, title, category);

  // العمود الأيسر: إطار لقطة الشاشة
  slide.addShape(SHAPE_ROUND_RECT, {
    x: 0.6, y: 1.15, w: 6.2, h: 5.75,
    rectRadius: 0.12,
    fill: { color: COLOR_CARD },
    line: { color: COLOR_GOLD, width: 1.2 }
  });

  const imagePath = path.join(screenshotsDir, screenshotName);
  if (fs.existsSync(imagePath)) {
    slide.addImage({
      path: imagePath,
      x: 0.75, y: 1.3, w: 5.9, h: 3.75,
      sizing: { type: 'contain', w: 5.9, h: 3.75 }
    });
  }

  // بطاقة وصف الواجهة أسفل الصورة
  slide.addShape(SHAPE_ROUND_RECT, {
    x: 0.75, y: 5.2, w: 5.9, h: 1.55,
    rectRadius: 0.08,
    fill: { color: COLOR_GOLD_LIGHT },
    line: { color: COLOR_GOLD, width: 0.8 }
  });

  slide.addText('📌 الوصف العام للشاشة:', {
    x: 0.85, y: 5.25, w: 5.7, h: 0.3,
    fontSize: 11, bold: true, color: COLOR_PRIMARY,
    rtl: true, align: 'right', fontFace: 'Calibri'
  });

  slide.addText(descText, {
    x: 0.85, y: 5.55, w: 5.7, h: 1.1,
    fontSize: 10.5, color: COLOR_TEXT,
    rtl: true, align: 'right', fontFace: 'Calibri',
    lineSpacingMultiple: 1.15
  });

  // العمود الأيمن: تحليل الأزرار والمهام
  // الصندوق 1: شريط الأزرار الهامة ووظائفها
  slide.addShape(SHAPE_ROUND_RECT, {
    x: 7.0, y: 1.15, w: 5.7, h: 4.35,
    rectRadius: 0.12,
    fill: { color: COLOR_CARD },
    line: { color: COLOR_BORDER, width: 1 }
  });

  slide.addShape(SHAPE_RECT, {
    x: 7.0, y: 1.15, w: 5.7, h: 0.5,
    fill: { color: COLOR_PRIMARY },
    line: { color: COLOR_PRIMARY }
  });

  slide.addText('🎯 وظائف الأزرار الرئيسية في هذه الصفحة:', {
    x: 7.15, y: 1.2, w: 5.4, h: 0.4,
    fontSize: 13, bold: true, color: COLOR_GOLD,
    rtl: true, align: 'right', fontFace: 'Calibri'
  });

  let btnY = 1.75;
  buttonsList.forEach((btn, idx) => {
    slide.addShape(SHAPE_ROUND_RECT, {
      x: 7.15, y: btnY, w: 5.4, h: 0.75,
      rectRadius: 0.06,
      fill: { color: idx % 2 === 0 ? 'F8FAFC' : 'F1F5F9' },
      line: { color: 'CBD5E1', width: 0.5 }
    });

    slide.addText(`🔘 زر [ ${btn.name} ]`, {
      x: 7.25, y: btnY + 0.05, w: 5.2, h: 0.28,
      fontSize: 11, bold: true, color: COLOR_PRIMARY,
      rtl: true, align: 'right', fontFace: 'Calibri'
    });

    slide.addText(btn.action, {
      x: 7.25, y: btnY + 0.33, w: 5.2, h: 0.38,
      fontSize: 9.8, color: COLOR_TEXT,
      rtl: true, align: 'right', fontFace: 'Calibri'
    });

    btnY += 0.83;
  });

  // الصندوق 2: الأثر الأمني والتنظيمي الميداني
  slide.addShape(SHAPE_ROUND_RECT, {
    x: 7.0, y: 5.65, w: 5.7, h: 1.25,
    rectRadius: 0.1,
    fill: { color: 'E8F2EE' },
    line: { color: COLOR_PRIMARY, width: 1.2 }
  });

  slide.addText('🛡️ الأثر الميداني وغرفة العمليات:', {
    x: 7.15, y: 5.72, w: 5.4, h: 0.28,
    fontSize: 11, bold: true, color: COLOR_PRIMARY,
    rtl: true, align: 'right', fontFace: 'Calibri'
  });

  slide.addText(impactText, {
    x: 7.15, y: 6.0, w: 5.4, h: 0.85,
    fontSize: 10, color: COLOR_PRIMARY,
    rtl: true, align: 'right', fontFace: 'Calibri',
    lineSpacingMultiple: 1.15
  });

  return slide;
}

