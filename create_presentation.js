pres.layout = 'WIDE_16_9';

const SHAPE_RECT = pres.shapes.RECTANGLE;
const SHAPE_ROUND_RECT = pres.shapes.ROUNDED_RECTANGLE;
const SHAPE_OVAL = pres.shapes.OVAL;

// الألوان الرئيسية المعتمدة من هوية الموقع
